// Made-up patients only. Dx and Meds buttons with the chart from the computer (APP-11-22-CHART), against the real receiver.
const { chromium, devices } = require('playwright');
const fs = require('fs');
let pass = 0, fail = 0;
const ok = (c, m) => { if (c) { pass++; } else { fail++; console.log('FAIL', m); } };
const U = 'http://127.0.0.1:8770/';
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ ...devices['Pixel 7'], serviceWorkers: 'block' });
  const page = await ctx.newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
  let chartCalls = 0; page.on('request', (r) => { if (r.url().includes('/api/chart')) chartCalls++; });
  await page.goto(U + 'index.html'); await page.waitForSelector('[data-act="add-building"]');
  await page.click('[data-act="add-building"]'); await page.fill('#new-building', 'Test Hall'); await page.click('[data-act="save-building"]'); await page.waitForTimeout(400);
  await page.evaluate(async () => { const s = await import('./js/store.js'); const st = await s.getSettings(); await s.saveSettings({ ...st, receiverToken: 'tok' }); });
  await page.reload(); await page.waitForSelector('[data-act="add-pt"]');
  await page.fill('#date', '2026-11-22'); await page.dispatchEvent('#date', 'change'); await page.waitForTimeout(300);
  const addPt = async (l, f, m) => { await page.click('[data-act="add-pt"]'); await page.fill('#ap-last', l); await page.fill('#ap-first', f); await page.fill('#ap-mrn', m); await page.click('[data-act="add-pt-save"]'); await page.waitForTimeout(300); };
  await addPt('Mouse', 'Mickey', '9001'); await addPt('Duck', 'Donald', '9002'); await addPt('Goof', 'Goofy', '9003');
  ok(chartCalls >= 1, 'the chart is asked for when the app opens (' + chartCalls + ' call(s))');
  const stored = await page.evaluate(async () => { const s = await import('./js/store.js'); const c = await s.getCharts(); return Object.values(c).map((x) => x.chart.patients.length); });
  ok(stored.length === 1 && stored[0] === 2, 'and is kept on the phone: ' + JSON.stringify(stored));
  const openPt = async (i) => { await page.locator('[data-act="open"]').nth(i).click(); await page.waitForSelector('[data-act="loc"]'); await page.click('[data-act="loc"]'); await page.click('[data-act="pain-pick"][data-v="2"]'); await page.click('button.primary[data-act="pain"]'); await page.waitForSelector('#note'); };
  await openPt(0);
  ok(await page.isVisible('[data-dkey="dx"]') && await page.isVisible('[data-dkey="meds"]'), 'the note screen has Dx and Meds buttons');
  await page.click('[data-dkey="dx"]'); await page.waitForSelector('[data-tap="dx"]');
  const dxPanel = await page.textContent('.dpanel');
  ok(dxPanel.includes('Diagnoses from the note 11/21/2026'), 'Dx shows where and when the diagnoses came from');
  ok(dxPanel.includes('Chart made 11/22/2026 18:59') && dxPanel.includes('pulled'), 'and when the chart was made and pulled');
  const dxBtns = await page.locator('[data-tap="dx"]').allTextContents();
  ok(JSON.stringify(dxBtns.map((x) => x.trim())) === JSON.stringify(['Hypertension', 'Type 2 diabetes', 'UTI "complicated" <E. coli>']), 'the diagnoses are listed word for word, in order: ' + JSON.stringify(dxBtns));
  await page.screenshot({ path: require('os').tmpdir() + '/shot_dx.png' });
  await page.locator('[data-tap="dx"]').nth(1).click(); await page.waitForTimeout(150);
  await page.locator('[data-tap="dx"]').nth(0).click(); await page.waitForTimeout(150);
  await page.locator('[data-tap="dx"]').nth(2).click(); await page.waitForTimeout(400);
  ok((await page.locator('[data-tap="dx"].on').count()) === 3, 'tapped diagnoses are marked');
  ok((await page.textContent('[data-dkey="dx"]')).includes('3'), 'the Dx button shows how many are tapped');
  const prev = await page.textContent('#detail-preview');
  ok(prev.includes('Dx: Type 2 diabetes') && prev.includes('Dx: UTI "complicated" <E. coli>'), '"As it will be sent" shows the Dx lines');
  await page.locator('[data-tap="dx"]').nth(2).click(); await page.waitForTimeout(400);
  ok((await page.locator('[data-tap="dx"].on').count()) === 2, 'tapping one again takes it off');
  const noteBefore = await page.inputValue('#note');
  await page.click('[data-dkey="meds"]'); await page.waitForSelector('[data-tap="meds"]');
  const medPanel = await page.textContent('.dpanel');
  ok(medPanel.includes('Medications from the Medications file 11/22/2026'), 'Meds shows where and when the list came from');
  ok(medPanel.includes('Give 1 tablet by mouth one time a day, for HTN (on hold)'), 'each medication shows its directions (and on hold)');
  await page.screenshot({ path: require('os').tmpdir() + '/shot_meds.png' });
  await page.locator('[data-tap="meds"]').nth(2).click(); await page.waitForTimeout(400);
  ok((await page.inputValue('#note')) === noteBefore, 'tapping does not change the note text itself');
  const lines = await page.evaluate(async () => {
    const n = await import('./js/note.js'); const s = await import('./js/store.js');
    const b = (await s.getSettings()).currentBuilding; const day = await s.getDay('2026-11-22', b);
    return { lines: n.summaryLines({ ...day, building: 'Test Hall' }), hash: n.noteHash(day.patients[0]), plain: n.noteHash({ ...day.patients[0], tapDx: undefined, tapMeds: undefined }) };
  });
  ok(lines.lines[3].startsWith('MOUSE, MICKEY (9001): ') && !/Dx:|Med:/.test(lines.lines[3]), 'the patient line has no Dx / Med words in it');
  ok(lines.lines[4] === 'Dx: Type 2 diabetes' && lines.lines[5] === 'Dx: Hypertension' && lines.lines[6] === 'Med: Jardiance Oral Tablet 10 MG (Empagliflozin)', 'the lines under the patient: one per item, in the order tapped: ' + JSON.stringify(lines.lines.slice(4, 7)));
  ok(lines.lines[7].startsWith('DUCK, DONALD (9002):'), 'then the next patient');
  ok(lines.hash !== lines.plain, 'a tapped item counts as a change to send');
  await page.click('[data-dclose]'); await page.click('[data-act="done"]'); await page.waitForSelector('[data-act="open"]');
  // a patient who is not in the chart, and one with empty lists
  await openPt(1);
  await page.click('[data-dkey="dx"]'); await page.waitForTimeout(300);
  ok((await page.textContent('.dpanel')).includes('Duck, Donald (9002) is not in the chart made 11/22/2026 18:59'), 'a patient not in the chart: said plainly, nothing to tap');
  ok((await page.locator('[data-tap]').count()) === 0, 'and no buttons from another patient are shown');
  await page.click('[data-dclose]'); await page.click('[data-act="done"]'); await page.waitForSelector('[data-act="open"]');
  await openPt(2);
  await page.click('[data-dkey="meds"]'); await page.waitForTimeout(300);
  ok((await page.textContent('.dpanel')).includes('No medications were found there'), 'a patient with an empty list: said plainly');
  await page.click('[data-dclose]'); await page.click('[data-act="done"]'); await page.waitForSelector('[data-act="open"]');
  // send to the real receiver and read the Word file it saved
  await page.click('[data-act="send"]'); await page.waitForTimeout(1500);
  const daily = process.env.BEDSIDE_OUT + '/Test Hall/Daily'; const files = fs.existsSync(daily) ? fs.readdirSync(daily).filter((f) => f.endsWith('.docx')) : [];
  ok(files.length === 1, 'the day was sent and saved by the receiver: ' + files.join(', '));
  if (files.length) fs.copyFileSync(daily + '/' + files[0], '' + require('os').tmpdir() + '/sent85.docx');
  // the chart on the phone outlives a reload with the computer unreachable
  await page.route('**/api/chart**', (r) => r.abort());
  await page.reload(); await page.waitForSelector('[data-act="open"]');
  await page.locator('[data-act="open"]').nth(0).click(); await page.waitForSelector('#note');
  await page.click('[data-dkey="dx"]'); await page.waitForSelector('[data-tap="dx"]');
  ok((await page.locator('[data-tap="dx"].on').count()) === 2 && (await page.locator('[data-tap="dx"]').count()) === 3, 'with the computer unreachable the chart on the phone still works, with what was tapped');
  await page.click('[data-chart="refresh"]'); await page.waitForTimeout(5500);
  const miss = await page.textContent('.dpanel');
  ok(miss.includes('Using the chart saved on this phone') && miss.includes('The computer could not be reached after 3 tries') && (await page.locator('[data-tap="dx"]').count()) === 3, 'Refresh with no computer: says it is using the saved chart and why, and keeps the chart (APP-11-25F)');
  // APP-11-25F: the first two tries get no answer, the third does - the chart arrives with no error shown
  await page.unroute('**/api/chart**');
  let tries = 0;
  await page.route('**/api/chart**', (r) => { tries++; if (tries <= 2) r.abort(); else r.continue(); });
  await page.click('[data-chart="refresh"]'); await page.waitForTimeout(6000);
  ok(tries === 3 && !(await page.$('#chartsaved')) && (await page.locator('[data-tap="dx"]').count()) === 3, 'two misses then an answer: the app tried 3 times and the chart came through with no error (' + tries + ' tries)');
  await page.unroute('**/api/chart**');
  await page.route('**/api/chart**', (r) => r.fulfill({ status: 404, body: 'Not found' }));
  await page.click('[data-chart="refresh"]'); await page.waitForTimeout(600);
  ok((await page.textContent('.dpanel')).includes('older one with no chart'), 'an older receiver: said plainly');
  await page.unroute('**/api/chart**');
  await page.route('**/api/chart**', (r) => r.fulfill({ status: 401, contentType: 'application/json', body: '{"ok":false}' }));
  await page.click('[data-chart="refresh"]'); await page.waitForTimeout(600);
  ok((await page.textContent('.dpanel')).includes('rejected the token'), 'a wrong token: said plainly');
  await page.unroute('**/api/chart**');
  await page.click('[data-chart="refresh"]'); await page.waitForTimeout(800);
  ok(!(await page.textContent('.dpanel')).includes('last try'), 'Refresh with the computer back: the chart is updated and the message is gone');
  await page.click('[data-dclear]'); await page.waitForTimeout(400);
  ok((await page.locator('[data-tap="dx"].on').count()) === 0 && !(await page.textContent('#detail-preview')).includes('Dx:'), 'Clear takes off all tapped diagnoses (medications are left)');
  ok((await page.textContent('#detail-preview')).includes('Med: Jardiance'), 'the tapped medication is still there');
  ok(errors.length === 0, 'no page errors: ' + errors.join(' | '));
  console.log(`ui chart: ${pass} passed, ${fail} failed`);
  await browser.close(); process.exit(fail ? 1 : 0);
})();
