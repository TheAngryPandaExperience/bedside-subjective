// Made-up patients only. Drives the real app: the added O2 / BM choices, the Ordered button, folding the Time and Not sent cards (APP-11-25B).
const { chromium, devices } = require('playwright');
let pass = 0, fail = 0;
const ok = (c, m) => { if (c) { pass++; } else { fail++; console.log('FAIL', m); } };
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ ...devices['Pixel 7'], serviceWorkers: 'block' });
  const page = await ctx.newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
  await page.goto('http://127.0.0.1:8765/index.html'); await page.waitForSelector('[data-act="add-building"]');
  await page.click('[data-act="add-building"]'); await page.fill('#new-building', 'Test Hall'); await page.click('[data-act="save-building"]'); await page.waitForTimeout(400);
  const addPt = async (date, last, mrn) => {
    await page.fill('#date', date); await page.dispatchEvent('#date', 'change'); await page.waitForTimeout(250);
    await page.click('[data-act="add-pt"]'); await page.fill('#ap-last', last); await page.fill('#ap-first', 'Pat'); await page.fill('#ap-mrn', mrn);
    await page.click('[data-act="add-pt-save"]'); await page.waitForTimeout(300);
    await page.click('[data-act="open"]'); await page.waitForSelector('[data-act="loc"]');
    await page.click('[data-act="loc"]'); await page.click('[data-act="pain-pick"][data-v="2"]');
    await page.click('button.primary[data-act="pain"]'); await page.waitForSelector('#note');
  };
  // a note left unsent on an earlier day, so the Not sent card has something to show
  await addPt('2026-11-24', 'Goof', '9003');
  await page.goBack(); await page.waitForSelector('[data-act="add-pt"]');
  await addPt('2026-11-25', 'Duck', '9002');
  const prev = async () => (await page.textContent('#detail-preview')) || '';
  const tap = async (sel) => { await page.click(sel); await page.waitForTimeout(220); };
  // ---- O2
  await page.click('.dchip[data-dkey="o2"]'); await page.waitForSelector('[data-pick="o2.room"]');
  await tap('[data-o2l="2"]'); await tap('[data-pick="o2.via"][data-v="nasal cannula"]'); await tap('[data-pick="o2.when"][data-v="continuous"]');
  ok((await prev()).includes('Pt on 2 L O2 via nasal cannula, continuous.'), 'liters + nasal cannula + continuous: ' + (await page.textContent('#o2hint')));
  await tap('[data-pick="o2.when"][data-v="at night only"]');
  ok((await prev()).includes('Pt on 2 L O2 via nasal cannula, at night only.'), 'another "when" replaces it');
  await tap('[data-pick="o2.room"]');
  ok((await prev()).includes('Pt on room air.') && !(await prev()).includes('L O2') && !(await prev()).includes('nasal cannula'), 'Room air clears the liters, how and when');
  ok(!(await page.$('[data-o2l].on')), 'and no liters button stays lit');
  await tap('[data-o2l="3"]');
  ok((await prev()).includes('Pt on 3 L O2.') && !(await prev()).includes('room air'), 'tapping liters takes Room air off');
  await tap('[data-pick="o2.pap"][data-v="CPAP"]'); await tap('[data-pick="o2.wean"]');
  await tap('[data-pick="o2.cough"][data-v="dry"]'); await tap('[data-pick="o2.wheeze"][data-v="denies"]');
  ok((await prev()).includes('Pt on 3 L O2. Pt uses CPAP. Weaning O2 as tolerated. Pt reports dry cough. Pt denies wheezing.'), 'CPAP, weaning, cough, wheezing: ' + (await page.textContent('#o2hint')));
  await tap('[data-pick="o2.cough"][data-v="productive"]');
  ok((await prev()).includes('Pt reports productive cough.') && !(await prev()).includes('dry cough'), 'one cough choice at a time');
  await page.screenshot({ path: require('os').tmpdir() + '/shot_o2b.png', fullPage: true });
  // ---- BM panel
  await page.click('.dchip[data-dkey="bm"]'); await page.waitForSelector('[data-pick="gu.gi"]');
  await tap('[data-pick="gu.gi"][data-v="nausea"]'); await tap('[data-pick="gu.gi"][data-v="bloating"]');
  ok((await prev()).includes('Pt complains of nausea and bloating.'), 'bowel complaints');
  await tap('[data-gusx="urgency"]'); await tap('[data-gusx="nocturia"]'); await tap('[data-pick="gu.urine"][data-v="cloudy"]');
  ok((await prev()).includes('Pt complains of nausea and bloating. Pt complains of urgency and nocturia. Urine cloudy.'), 'urinary complaints and urine: ' + (await page.textContent('#guhint')));
  ok(await page.isDisabled('[data-pick="gu.cathSx"][data-v="leaking"]') && await page.isDisabled('[data-pick="gu.drain"]') && await page.isDisabled('[data-pick="gu.output"][data-v="formed"]') && await page.isDisabled('[data-pick="gu.pegOk"]'),
    'catheter, ostomy and PEG extras wait for their main choice');
  ok(JSON.stringify(await page.$$eval('[data-gucath]', (els) => els.map((e) => e.dataset.gucath))) === JSON.stringify(['Foley', 'Suprapubic', 'Nephrostomy', 'Condom', 'Straight cath']), 'five catheter choices');
  await tap('[data-gucath="Nephrostomy"]');
  ok((await prev()).includes('Nephrostomy tube in place, denies any complications.'), 'Nephrostomy');
  await tap('[data-pick="gu.cathSx"][data-v="leaking"]');
  ok((await prev()).includes('Nephrostomy tube in place, complains of leaking.') && !(await prev()).includes('tube in place, denies'), 'a catheter complaint turns "denies" off');
  await tap('[data-gucathok]');
  ok((await prev()).includes('Nephrostomy tube in place, denies any complications.') && !(await prev()).includes('leaking'), 'and "denies" clears the complaint');
  await tap('[data-pick="gu.drain"]'); await tap('[data-pick="gu.trial"]');
  ok((await prev()).includes('Draining clear yellow urine. Voiding trial planned.'), 'draining and voiding trial');
  await tap('[data-guost="Urostomy"]'); await tap('[data-pick="gu.ostOk"]'); await tap('[data-pick="gu.stoma"]'); await tap('[data-pick="gu.output"][data-v="high output"]'); await tap('[data-pick="gu.skin"][data-v="irritated"]');
  ok((await prev()).includes('Urostomy in place, denies any complications. Stoma pink and moist. High output. Skin around stoma irritated.'), 'ostomy extras: ' + (await page.textContent('#guhint')).slice(-120));
  await tap('[data-pick="gu.peg"]'); await tap('[data-pick="gu.pegOk"]');
  ok((await prev()).includes('PEG tube in place, site clean and dry.'), 'PEG tube');
  await page.screenshot({ path: require('os').tmpdir() + '/shot_bmb.png', fullPage: true });
  await tap('[data-guost="Urostomy"]');
  ok(!(await prev()).includes('Stoma') && !(await prev()).includes('High output') && !(await prev()).includes('Skin around'), 'taking the ostomy off takes its extras off');
  await tap('[data-gucath="Nephrostomy"]');
  ok(!(await prev()).includes('Draining') && !(await prev()).includes('Voiding trial'), 'taking the catheter off takes its extras off');
  // ---- Ordered
  const chips = await page.$$eval('.dchip', (els) => els.map((e) => e.dataset.dkey));
  ok(chips.indexOf('ordered') === chips.indexOf('labs') + 1, 'there is an Ordered button after Labs: ' + chips.join(','));
  await page.click('.dchip[data-dkey="ordered"]'); await page.waitForSelector('[data-pick="ordered.labs"]');
  await tap('[data-pick="ordered.labs"][data-v="CBC"]'); await tap('[data-pick="ordered.labs"][data-v="BMP"]'); await tap('[data-pick="ordered.tests"][data-v="CXR"]');
  ok((await prev()).trim().endsWith('Ordered CBC, BMP and CXR.'), 'labs and CXR, at the end of the note: ' + (await prev()).slice(-40));
  await tap('[data-pick="ordered.tests"][data-v="KUB"]'); await tap('[data-pick="ordered.us"][data-v="abdomen"]');
  await tap('[data-pick="ordered.dopSide"][data-v="left"]');
  ok(!(await prev()).includes('doppler'), 'the doppler waits until upper or lower is picked');
  await tap('[data-pick="ordered.dopLimb"][data-v="lower"]');
  ok((await prev()).includes('Ordered CBC, BMP, CXR, KUB, ultrasound of abdomen and ultrasound doppler of left lower extremity.'), 'KUB, ultrasound, doppler: ' + (await page.textContent('#ordhint')));
  await page.fill('#ordus', 'right upper quadrant'); await page.waitForTimeout(500);
  await page.fill('#ordother', 'EKG'); await page.waitForTimeout(500);
  ok((await prev()).includes('ultrasound of abdomen, ultrasound of right upper quadrant, ultrasound doppler of left lower extremity and EKG.'), 'a typed area and a typed order');
  await page.screenshot({ path: require('os').tmpdir() + '/shot_ordered.png', fullPage: true });
  await tap('[data-pick="ordered.labs"][data-v="CBC"]');
  ok(!(await prev()).includes('CBC'), 'tapping an item again takes it off');
  ok((await page.textContent('.dchip[data-dkey="ordered"]')).includes('7'), 'the Ordered button shows how many: ' + (await page.textContent('.dchip[data-dkey="ordered"]')).trim());
  await page.click('[data-dclear]'); await page.waitForTimeout(250);
  ok(!(await prev()).includes('Ordered'), 'Clear empties the Ordered button');
  ok(errors.length === 0, 'no page errors: ' + errors.join(' | '));
  // ---- folding the two cards on the list screen
  await page.goBack(); await page.waitForSelector('#clock [data-act="fold"]');
  ok(await page.isVisible('[data-act="clock-in"]') && (await page.textContent('#unsent')).includes('Not sent from other days') && await page.isVisible('#unsent [data-act="goto-day"]'), 'both cards start open');
  await page.click('#clock [data-act="fold"]'); await page.waitForTimeout(300);
  ok(!(await page.$('[data-act="clock-in"]')) && (await page.textContent('#clock')).includes('Time at Test Hall') && (await page.textContent('#clock')).includes('Not clocked in'), 'the Time card folds to its heading');
  await page.click('#unsent [data-act="fold"]'); await page.waitForTimeout(300);
  ok(!(await page.$('#unsent [data-act="goto-day"]')) && /Not sent from other days \(1 note on 1 day\)/.test(await page.textContent('#unsent')), 'the Not sent card folds to its heading with the count: ' + (await page.textContent('#unsent')).trim());
  await page.screenshot({ path: require('os').tmpdir() + '/shot_folded.png' });
  await page.reload(); await page.waitForSelector('#clock [data-act="fold"]'); await page.waitForTimeout(600);
  ok(!(await page.$('[data-act="clock-in"]')) && !(await page.$('#unsent [data-act="goto-day"]')), 'both stay folded after the app is closed and opened again');
  await page.click('#clock [data-act="fold"]'); await page.waitForTimeout(300);
  await page.click('[data-act="clock-in"]'); await page.waitForTimeout(300);
  ok((await page.textContent('#clock')).includes('Clocked in at'), 'unfolded again, the clock works');
  await page.click('#clock [data-act="fold"]'); await page.waitForTimeout(300);
  ok((await page.textContent('#clock')).includes('Clocked in at') && !(await page.$('[data-act="clock-out"]')), 'folded while clocked in, the heading still shows the clock-in time');
  await page.click('#unsent [data-act="fold"]'); await page.waitForTimeout(300);
  ok(await page.isVisible('#unsent [data-act="goto-day"]'), 'the Not sent card opens again');
  ok(errors.length === 0, 'no page errors at the end: ' + errors.join(' | '));
  console.log(`ui 11-25B: ${pass} passed, ${fail} failed`);
  await browser.close(); process.exit(fail ? 1 : 0);
})();
