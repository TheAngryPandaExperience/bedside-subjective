// Made-up patients only. Drives the real app: edema for each leg under Ext in the Exam button (APP-11-25D).
const { chromium, devices } = require('playwright');
let pass = 0, fail = 0;
const ok = (c, m) => { if (c) { pass++; } else { fail++; console.log('FAIL', m); } };
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ ...devices['Pixel 7'], serviceWorkers: 'block' });
  const page = await ctx.newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
  await page.goto('http://127.0.0.1:8765/index.html'); await page.waitForSelector('[data-act="add-building"]');
  await page.click('[data-act="add-building"]'); await page.fill('#new-building', 'Test Hall'); await page.click('[data-act="save-building"]'); await page.waitForTimeout(400);
  await page.fill('#date', '2026-11-25'); await page.dispatchEvent('#date', 'change'); await page.waitForTimeout(250);
  await page.click('[data-act="add-pt"]'); await page.fill('#ap-last', 'Duck'); await page.fill('#ap-first', 'Pat'); await page.fill('#ap-mrn', '9002');
  await page.click('[data-act="add-pt-save"]'); await page.waitForTimeout(300);
  await page.click('[data-act="open"]'); await page.waitForSelector('[data-act="loc"]');
  await page.click('[data-act="loc"]'); await page.click('[data-act="pain-pick"][data-v="2"]');
  await page.click('button.primary[data-act="pain"]'); await page.waitForSelector('#note');
  const prev = async () => (await page.textContent('#detail-preview')) || '';
  const tap = async (sel) => { await page.click(sel); await page.waitForTimeout(220); };
  await page.click('.dchip[data-dkey="exam"]'); await page.waitForSelector('[data-pick="edema.left"]');
  ok((await page.$$('[data-exsys="Ext"]')).length === 4, 'the four Ext choices from before are still there');
  ok(JSON.stringify(await page.$$eval('[data-pick="edema.left"]', (els) => els.map((x) => x.dataset.v))) === JSON.stringify(['none', 'trace', '1+', '2+', '3+', '4+']), 'each leg: none, trace, 1+ to 4+');
  ok(await page.isDisabled('[data-pick="edema.kind"][data-v="pitting"]'), 'pitting waits for a leg with edema');
  await tap('[data-pick="edema.left"][data-v="2+"]');
  ok((await prev()).includes('Exam: Ext: 2+ left lower leg edema') && !(await prev()).includes('right'), 'left 2+ alone: ' + (await page.textContent('#edhint')));
  await tap('[data-pick="edema.right"][data-v="none"]');
  ok((await prev()).includes('Exam: Ext: 2+ left lower leg edema, no right lower leg edema'), 'left 2+, right none');
  await tap('[data-pick="edema.kind"][data-v="pitting"]');
  ok((await prev()).includes('Exam: Ext: 2+ pitting left lower leg edema, no right lower leg edema'), 'pitting');
  await tap('[data-pick="edema.right"][data-v="2+"]');
  ok((await prev()).includes('Exam: Ext: 2+ pitting bilateral lower leg edema'), 'both legs the same becomes "bilateral"');
  await tap('[data-pick="edema.right"][data-v="trace"]');
  ok((await prev()).includes('2+ pitting left lower leg edema, trace pitting right lower leg edema'), 'left 2+, right trace');
  await page.screenshot({ path: require('os').tmpdir() + '/shot_edema.png', fullPage: true });
  // the old one-tap choices and the by-leg grades replace each other
  await tap('[data-exsys="Ext"][data-exv="No lower leg edema"]');
  ok((await prev()).includes('Exam: Ext: No lower leg edema') && !(await prev()).includes('left lower leg') && !(await page.$('[data-pick="edema.left"].on')), 'tapping an old edema choice clears the by-leg grades');
  await tap('[data-pick="edema.left"][data-v="1+"]');
  ok((await prev()).includes('Exam: Ext: 1+ left lower leg edema') && !(await prev()).includes('No lower leg edema') && (await page.inputValue('[data-exinput="Ext"]')) === '', 'tapping a leg grade clears the old edema choice');
  await page.fill('[data-exinput="Ext"]', 'Pedal pulses palpable'); await page.waitForTimeout(500);
  ok((await prev()).includes('Exam: Ext: Pedal pulses palpable. 1+ left lower leg edema'), 'typed Ext text is kept, with the edema after it');
  await tap('[data-pick="edema.left"][data-v="1+"]');
  ok((await prev()).includes('Exam: Ext: Pedal pulses palpable') && !(await prev()).includes('edema'), 'tapping the grade again takes it off; the typed text stays');
  await tap('[data-pick="edema.left"][data-v="3+"]'); await tap('[data-pick="edema.right"][data-v="1+"]');
  await page.goBack(); await page.waitForSelector('[data-act="open"]'); await page.click('[data-act="open"]'); await page.waitForSelector('#note');
  ok((await prev()).includes('Exam: Ext: Pedal pulses palpable. 3+ left lower leg edema, 1+ right lower leg edema'), 'saved: still there after leaving and coming back');
  await page.click('.dchip[data-dkey="exam"]'); await page.waitForSelector('[data-dclear]'); await page.click('[data-dclear]'); await page.waitForTimeout(250);
  ok(!(await prev()).includes('Exam:'), 'Clear on Exam clears the edema too');
  ok(errors.length === 0, 'no page errors: ' + errors.join(' | '));
  console.log(`ui 11-25D: ${pass} passed, ${fail} failed`);
  await browser.close(); process.exit(fail ? 1 : 0);
})();
