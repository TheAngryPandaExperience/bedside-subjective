// Made-up patients only. Drives the real app: the O2 button, and urinary / catheter / ostomy inside the BM button (APP-11-25).
const { chromium, devices } = require('playwright');
let pass = 0, fail = 0;
const ok = (c, m) => { if (c) { pass++; } else { fail++; console.log('FAIL', m); } };
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ ...devices['Pixel 7'], serviceWorkers: 'block' });
  const page = await ctx.newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
  await page.goto('http://127.0.0.1:8765/index.html'); await page.waitForSelector('[data-act="add-building"]');
  await page.click('[data-act="add-building"]'); await page.fill('#new-building', 'Test Hall'); await page.click('[data-act="save-building"]'); await page.waitForTimeout(400);
  await page.fill('#date', '2026-11-25'); await page.dispatchEvent('#date', 'change'); await page.waitForTimeout(200);
  await page.click('[data-act="add-pt"]'); await page.fill('#ap-last', 'Duck'); await page.fill('#ap-first', 'Daisy'); await page.fill('#ap-mrn', '9002');
  await page.click('[data-act="add-pt-save"]'); await page.waitForTimeout(300);
  await page.click('[data-act="open"]'); await page.waitForSelector('[data-act="loc"]');
  await page.click('[data-act="loc"]'); await page.click('[data-act="pain-pick"][data-v="2"]');
  await page.click('button.primary[data-act="pain"]'); await page.waitForSelector('#note');
  const prev = async () => (await page.textContent('#detail-preview')) || '';
  const chips = await page.$$eval('.dchip', (els) => els.map((e) => e.dataset.dkey));
  ok(chips.includes('o2') && chips.indexOf('o2') === chips.indexOf('bm') - 1, 'there is an O2 button, just before BM: ' + chips.join(','));
  // O2
  await page.click('.dchip[data-dkey="o2"]'); await page.waitForSelector('[data-o2l="2"]');
  ok(JSON.stringify(await page.$$eval('[data-o2l]', (els) => els.map((e) => e.dataset.o2l))) === JSON.stringify(['1', '2', '3', '4', '5', '6']), 'liters 1 to 6 to tap');
  await page.click('[data-o2l="2"]'); await page.waitForTimeout(250);
  ok((await prev()).includes('Pt on 2 L O2.'), 'tapping 2 writes "Pt on 2 L O2."');
  await page.click('[data-o2l="4"]'); await page.waitForTimeout(250);
  ok((await prev()).includes('Pt on 4 L O2.') && !(await prev()).includes('2 L O2'), 'another number replaces it');
  await page.click('[data-o2sob="denies"]'); await page.waitForTimeout(250);
  await page.click('[data-o2tx]'); await page.waitForTimeout(250);
  const note1 = await prev();
  ok(/breathing complications[^.]*\. Pt on 4 L O2\. Pt denies shortness of breath\. Continues breathing treatments as ordered\./.test(note1), 'the three sentences follow the breathing sentence: ' + note1.slice(0, 260));
  ok(!(await page.$('#o2clash')), 'no warning when the patient denies shortness of breath');
  await page.click('[data-o2sob="reports"]'); await page.waitForTimeout(250);
  ok((await prev()).includes('Pt reports shortness of breath.') && !(await prev()).includes('denies shortness'), 'Has shortness of breath replaces Denies');
  ok(!!(await page.$('#o2clash')), 'a warning shows that the note still says the patient denies breathing complications');
  await page.screenshot({ path: require('os').tmpdir() + '/shot_o2.png', fullPage: true });
  await page.click('[data-o2sob="reports"]'); await page.waitForTimeout(250);
  ok(!(await prev()).includes('shortness of breath'), 'tapping it again takes it off');
  await page.fill('#o2other', '2.5'); await page.waitForTimeout(500);
  ok((await prev()).includes('Pt on 2.5 L O2.'), 'a typed amount is used: 2.5');
  await page.fill('#o2other', 'two'); await page.waitForTimeout(500);
  ok(!(await prev()).includes('L O2') && (await page.textContent('#o2hint')).includes('as a number'), 'a typed word is not written, and the panel says why');
  await page.click('[data-o2l="3"]'); await page.waitForTimeout(250);
  ok((await page.textContent('.dchip[data-dkey="o2"]')).includes('3 L'), 'the O2 button shows what is set: ' + (await page.textContent('.dchip[data-dkey="o2"]')).trim());
  // BM panel: urinary, catheter, ostomy
  await page.click('.dchip[data-dkey="bm"]'); await page.waitForSelector('[data-gudenies]');
  ok(await page.isVisible('[data-bm="yesterday"]') && await page.isVisible('[data-bmkind="loose"]'), 'the BM choices are still there');
  await page.click('[data-gudenies]'); await page.waitForTimeout(250);
  ok((await prev()).includes('Pt denies urinary complications.'), 'Pt denies urinary complications');
  await page.click('[data-gusx="dysuria"]'); await page.waitForTimeout(250);
  await page.click('[data-gusx="blood in urine"]'); await page.waitForTimeout(250);
  ok((await prev()).includes('Pt complains of dysuria and blood in urine.') && !(await prev()).includes('denies urinary'), 'complaints replace "denies": ' + (await page.textContent('#guhint')));
  await page.click('[data-gudenies]'); await page.waitForTimeout(250);
  ok((await prev()).includes('Pt denies urinary complications.') && !(await prev()).includes('complains of'), 'and "denies" clears the complaints');
  ok(await page.isDisabled('[data-gucathok]'), '"Denies any complications" waits for Foley or Suprapubic');
  await page.click('[data-gucath="Foley"]'); await page.waitForTimeout(250);
  ok((await prev()).includes('Foley catheter in place, denies any complications.'), 'Foley: ' + (await page.textContent('#guhint')));
  await page.click('[data-gucath="Suprapubic"]'); await page.waitForTimeout(250);
  ok((await prev()).includes('Suprapubic catheter in place, denies any complications.') && !(await prev()).includes('Foley'), 'Suprapubic replaces Foley');
  await page.click('[data-gucathok]'); await page.waitForTimeout(250);
  ok((await prev()).includes('Suprapubic catheter in place.'), '"denies any complications" can be taken off');
  await page.click('[data-guost="Ileostomy"]'); await page.waitForTimeout(250);
  ok((await prev()).includes('Ileostomy in place.'), 'Ileostomy');
  ok(JSON.stringify(await page.$$eval('[data-guost]', (els) => els.map((e) => e.dataset.guost))) === JSON.stringify(['Colostomy', 'Ostomy', 'Ileostomy', 'Urostomy']), 'the four ostomy choices');
  await page.click('[data-bm="yesterday"]'); await page.waitForTimeout(250);
  const note2 = await prev();
  ok(/constipation[^.]*\. Last BM yesterday \(11\/24\/26\)\. Pt denies urinary complications\. Suprapubic catheter in place\. Ileostomy in place\./.test(note2), 'BM day, then urinary, catheter, ostomy after the constipation sentence: ' + note2.slice(-330));
  ok((await page.textContent('.dchip[data-dkey="bm"]')).includes('GU'), 'the BM button shows that urinary items are set');
  await page.screenshot({ path: require('os').tmpdir() + '/shot_gu.png', fullPage: true });
  // it survives leaving and coming back, and goes into the summary
  await page.goBack(); await page.waitForSelector('[data-act="open"]'); await page.click('[data-act="open"]'); await page.waitForSelector('#note');
  ok((await prev()).includes('Pt on 3 L O2.') && (await prev()).includes('Ileostomy in place.'), 'saved: still there after leaving the patient and coming back');
  await page.click('.dchip[data-dkey="bm"]'); await page.waitForSelector('[data-dclear]'); await page.click('[data-dclear]'); await page.waitForTimeout(250);
  ok(!(await prev()).includes('Last BM') && !(await prev()).includes('urinary') && !(await prev()).includes('Ileostomy') && (await prev()).includes('Pt on 3 L O2.'), 'Clear on BM clears BM, urinary, catheter and ostomy, and leaves O2');
  ok(errors.length === 0, 'no page errors: ' + errors.join(' | '));
  console.log(`ui 11-25: ${pass} passed, ${fail} failed`);
  await browser.close(); process.exit(fail ? 1 : 0);
})();
