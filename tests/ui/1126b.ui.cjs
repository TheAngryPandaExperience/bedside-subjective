// Made-up patients only. Things in a note that do not fit together: shown on the patient's screen and before sending (APP-11-26B).
const { chromium, devices } = require('playwright');
const fs = require('fs');
let pass = 0, fail = 0;
const ok = (c, m) => { if (c) { pass++; } else { fail++; console.log('FAIL', m); } };
const U = 'http://127.0.0.1:8770/';
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ ...devices['Pixel 7'], serviceWorkers: 'block' });
  await ctx.addInitScript(() => { Math.random = () => 0; });
  const page = await ctx.newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
  let sends = 0; page.on('request', (r) => { if (r.url().includes('/api/send')) sends++; });
  await page.goto(U + 'index.html'); await page.waitForSelector('[data-act="add-building"]');
  await page.click('[data-act="add-building"]'); await page.fill('#new-building', 'Clash Hall'); await page.click('[data-act="save-building"]'); await page.waitForTimeout(400);
  await page.evaluate(async () => { const s = await import('./js/store.js'); const st = await s.getSettings(); await s.saveSettings({ ...st, receiverToken: 'tok' }); });
  await page.reload(); await page.waitForSelector('[data-act="add-pt"]');
  await page.fill('#date', '2026-11-26'); await page.dispatchEvent('#date', 'change'); await page.waitForTimeout(300);
  const addPt = async (l, m) => { await page.click('[data-act="add-pt"]'); await page.fill('#ap-last', l); await page.fill('#ap-first', 'Pat'); await page.fill('#ap-mrn', m); await page.click('[data-act="add-pt-save"]'); await page.waitForTimeout(300); };
  await addPt('Duck', '9002'); await addPt('Goof', '9003');
  const openPt = async (i) => { await page.locator('[data-act="open"]').nth(i).click(); await page.waitForSelector('[data-act="loc"]'); await page.click('[data-act="loc"]'); await page.click('[data-act="pain-pick"][data-v="2"]'); await page.click('button.primary[data-act="pain"]'); await page.waitForSelector('#note'); };
  const tap = async (sel) => { await page.click(sel); await page.waitForTimeout(250); };
  await openPt(0);
  ok((await page.textContent('#clashbox')).trim() === '', 'a plain note shows no check box');
  await page.click('.dchip[data-dkey="o2"]'); await page.waitForSelector('[data-o2sob="reports"]');
  await tap('[data-o2sob="reports"]');
  const box = (await page.textContent('#clashbox')).replace(/\s+/g, ' ');
  ok(box.includes('these do not fit together') && box.includes('breathing') && box.includes('reports shortness of breath'), 'denies breathing complications + reports shortness of breath is shown under the note: ' + box.slice(0, 200));
  const noteBefore = await page.inputValue('#note');
  await page.click('.dchip[data-dkey="exam"]'); await page.waitForSelector('[data-pick="incision.state"]');
  await tap('[data-exsys="Skin"][data-exv="Warm, dry, intact"]'); await tap('[data-pick="incision.site"][data-v="hip"]'); await tap('[data-pick="incision.state"][data-v="intact"]');
  ok((await page.textContent('#clashbox')).includes('skin') && (await page.$$('#clashbox .clash div')).length === 2, 'a second pair (Skin intact + incision) is listed with the first');
  ok((await page.inputValue('#note')) === noteBefore, 'the note text is not changed by the check');
  await page.goBack(); await page.waitForSelector('[data-act="open"]');
  await openPt(1);
  await page.goBack(); await page.waitForSelector('[data-act="send"]');
  await page.click('[data-act="send"]'); await page.waitForSelector('[data-act="send-clashes"]');
  const gate = (await page.textContent('#app')).replace(/\s+/g, ' ');
  ok(gate.includes('Check before sending') && gate.includes('Nothing was sent') && gate.includes('1. Duck, Pat') && !gate.includes('2. Goof') && sends === 0, 'Send day stops first: names the patient and the pairs, and nothing is sent');
  await page.screenshot({ path: require('os').tmpdir() + '/shot_clash.png', fullPage: true });
  await page.click('[data-act="back"]'); await page.waitForSelector('[data-act="send"]');
  ok(sends === 0, '"Go back and fix them" sends nothing');
  // fix one, leave one, send anyway
  await page.locator('[data-act="open"]').nth(0).click(); await page.waitForSelector('#note');
  await page.click('.dchip[data-dkey="o2"]'); await page.waitForSelector('[data-o2sob="denies"]'); await tap('[data-o2sob="denies"]');
  ok(!(await page.textContent('#clashbox')).includes('breathing') && (await page.textContent('#clashbox')).includes('skin'), 'fixing one pair takes it off the list; the other stays');
  await page.goBack(); await page.waitForSelector('[data-act="send"]');
  await page.click('[data-act="send"]'); await page.waitForSelector('[data-act="send-clashes"]');
  await page.click('[data-act="send-clashes"]'); await page.waitForTimeout(2000);
  const daily = process.env.BEDSIDE_OUT + '/Clash Hall/Daily';
  const files = fs.existsSync(daily) ? fs.readdirSync(daily) : [];
  ok(sends === 1 && files.some((f) => f.endsWith('.docx')), '"Send anyway" sends the day as it is (' + files.join(', ') + ')');
  await page.click('[data-act="send"]').catch(() => {}); await page.waitForTimeout(600);
  ok(errors.length === 0, 'no page errors: ' + errors.join(' | '));
  console.log(`ui 11-26B: ${pass} passed, ${fail} failed`);
  await browser.close(); process.exit(fail ? 1 : 0);
})();
