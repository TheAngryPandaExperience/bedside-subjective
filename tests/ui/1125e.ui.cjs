// Made-up patients only. Drives the real app: "Put in note" on each body system of the Exam button (APP-11-25E).
const { chromium, devices } = require('playwright');
let pass = 0, fail = 0;
const ok = (c, m) => { if (c) { pass++; } else { fail++; console.log('FAIL', m); } };
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ ...devices['Pixel 7'], serviceWorkers: 'block' });
  const page = await ctx.newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
  await page.goto('http://127.0.0.1:8765/index.html'); await page.waitForSelector('[data-act="add-building"]');
  await page.click('[data-act="add-building"]'); await page.fill('#new-building', 'Test Hall'); await page.click('[data-act="save-building"]'); await page.waitForTimeout(400);
  await page.fill('#date', '2026-11-25'); await page.dispatchEvent('#date', 'change'); await page.waitForTimeout(250);
  await page.click('[data-act="add-pt"]'); await page.fill('#ap-last', 'Duck'); await page.fill('#ap-first', 'Pat'); await page.fill('#ap-mrn', '9002');
  await page.click('[data-act="add-pt-save"]'); await page.waitForTimeout(300);
  await page.click('[data-act="open"]'); await page.waitForSelector('[data-act="loc"]');
  await page.click('[data-act="loc"]'); await page.click('[data-act="pain-pick"][data-v="2"]');
  await page.click('button.primary[data-act="pain"]'); await page.waitForSelector('#note');
  const prev = async () => (await page.textContent('#detail-preview')) || '';
  const tap = async (sel) => { await page.click(sel); await page.waitForTimeout(220); };
  await page.click('.dchip[data-dkey="exam"]'); await page.waitForSelector('[data-pick="exn.sys"]');
  ok((await page.$$('[data-pick="exn.sys"]')).length === 9, 'each of the nine body systems has a "Put in note" switch');
  await tap('[data-exsys="Resp"][data-exv="Diminished at the bases"]'); await tap('[data-exsys="CV"][data-exv="RRR, no murmur"]');
  ok(!(await prev()).includes('On exam'), 'findings alone do not go in the note text');
  await tap('[data-pick="exn.sys"][data-v="Resp"]');
  const a = await prev();
  ok(a.includes('On exam: Resp diminished at the bases.') && a.includes('Exam: Resp: Diminished at the bases') && a.includes('Exam: CV: RRR, no murmur'), 'Resp ticked: the sentence is in the note, and both exam lines still go out');
  ok(a.indexOf('On exam:') < a.indexOf('Exam: Resp:'), 'the sentence is in the note text, above the exam lines');
  await tap('[data-pick="edema.left"][data-v="2+"]'); await tap('[data-pick="edema.right"][data-v="none"]'); await tap('[data-pick="exn.sys"][data-v="Ext"]');
  ok((await prev()).includes('On exam: Resp diminished at the bases; Ext 2+ left lower leg edema, no right lower leg edema.'), 'Resp and Ext: ' + (await prev()).split('On exam:')[1].split('.')[0]);
  await tap('[data-pick="exn.sys"][data-v="Skin"]');
  ok((await prev()).includes('no right lower leg edema.') && !(await prev()).includes('; Skin'), 'a ticked system with no finding is left out');
  await tap('[data-exsys="Resp"][data-exv="Bibasilar crackles"]');
  ok((await prev()).includes('On exam: Resp bibasilar crackles;') && (await prev()).includes('Exam: Resp: Bibasilar crackles'), 'change the finding and both places change together');
  await page.fill('[data-exinput="Skin"]', 'Dressing clean, dry, intact'); await page.waitForTimeout(500);
  ok((await prev()).includes('; Skin dressing clean, dry, intact.'), 'a typed finding for a ticked system is added');
  await page.screenshot({ path: require('os').tmpdir() + '/shot_onexam.png', fullPage: true });
  await tap('[data-pick="exn.sys"][data-v="Resp"]');
  ok(!(await prev()).includes('On exam: Resp') && (await prev()).includes('On exam: Ext 2+') && (await prev()).includes('Exam: Resp: Bibasilar crackles'), 'unticking takes it out of the note text only');
  await page.goBack(); await page.waitForSelector('[data-act="open"]'); await page.click('[data-act="open"]'); await page.waitForSelector('#note');
  ok((await prev()).includes('On exam: Ext 2+ left lower leg edema, no right lower leg edema; Skin dressing clean, dry, intact.'), 'saved: still there after leaving and coming back');
  await page.click('.dchip[data-dkey="exam"]'); await page.waitForSelector('[data-dclear]'); await page.click('[data-dclear]'); await page.waitForTimeout(250);
  ok(!(await prev()).includes('On exam') && !(await page.$('[data-pick="exn.sys"].on')), 'Clear on Exam clears the ticks too');
  ok(errors.length === 0, 'no page errors: ' + errors.join(' | '));
  console.log(`ui 11-25E: ${pass} passed, ${fail} failed`);
  await browser.close(); process.exit(fail ? 1 : 0);
})();
