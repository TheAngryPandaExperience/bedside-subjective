// Made-up patients only. Sections that fold inside the long panels, and the "Most used" row (APP-11-26C).
const { chromium, devices } = require('playwright');
let pass = 0, fail = 0;
const ok = (c, m) => { if (c) { pass++; } else { fail++; console.log('FAIL', m); } };
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ ...devices['Pixel 7'], serviceWorkers: 'block' });
  const page = await ctx.newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
  await page.goto('http://127.0.0.1:8765/index.html'); await page.waitForSelector('[data-act="add-building"]');
  await page.click('[data-act="add-building"]'); await page.fill('#new-building', 'Test Hall'); await page.click('[data-act="save-building"]'); await page.waitForTimeout(400);
  await page.fill('#date', '2026-11-26'); await page.dispatchEvent('#date', 'change'); await page.waitForTimeout(250);
  const addPt = async (l, m) => { await page.click('[data-act="add-pt"]'); await page.fill('#ap-last', l); await page.fill('#ap-first', 'Pat'); await page.fill('#ap-mrn', m); await page.click('[data-act="add-pt-save"]'); await page.waitForTimeout(300); };
  await addPt('Duck', '9002'); await addPt('Goof', '9003');
  const openPt = async (i) => { await page.locator('[data-act="open"]').nth(i).click(); await page.waitForSelector('[data-act="loc"]'); await page.click('[data-act="loc"]'); await page.click('[data-act="pain-pick"][data-v="2"]'); await page.click('button.primary[data-act="pain"]'); await page.waitForSelector('#note'); };
  const prev = async () => (await page.textContent('#detail-preview')) || '';
  const tap = async (sel) => { await page.click(sel); await page.waitForTimeout(220); };
  await openPt(0);
  await page.click('.dchip[data-dkey="bm"]'); await page.waitForSelector('[data-sfold="bm.cath"]');
  const secs = await page.$$eval('.psec', (els) => els.map((e) => e.dataset.sec));
  ok(JSON.stringify(secs) === JSON.stringify(['bm.bm', 'bm.bowel', 'bm.urinary', 'bm.cath', 'bm.ostomy', 'bm.peg']), 'the BM panel has six sections: ' + secs.join(', '));
  ok(await page.isVisible('[data-gucath="Foley"]') && await page.isVisible('[data-guost="Colostomy"]'), 'every section starts open');
  const tall = (await page.$eval('.dpanel', (e) => e.getBoundingClientRect().height));
  await tap('[data-gucath="Foley"]'); await tap('[data-pick="gu.drain"]');
  await tap('[data-sfold="bm.cath"]');
  ok(!(await page.isVisible('[data-gucath="Foley"]')), 'tapping the Catheter heading folds it');
  const head = (await page.textContent('[data-sfold="bm.cath"]')).replace(/\s+/g, ' ');
  ok(head.includes('Foley catheter in place, denies any complications. Draining clear yellow urine.'), 'the folded heading says what is set in it: ' + head);
  ok((await prev()).includes('Foley catheter in place, denies any complications. Draining clear yellow urine.'), 'what is set in a folded section is still in the note');
  await tap('[data-sfoldall="bm"]');
  const shut = await page.$$eval('.psec-body', (els) => els.filter((e) => e.hidden).length);
  const small = (await page.$eval('.dpanel', (e) => e.getBoundingClientRect().height));
  ok(shut === 6 && small < tall / 3 && (await page.textContent('[data-sfoldall="bm"]')).trim() === 'Open all', `Fold all folds all six; the panel is ${Math.round(small)}px tall, was ${Math.round(tall)}px`);
  await page.screenshot({ path: require('os').tmpdir() + '/shot_folded_bm.png' });
  await tap('[data-sfold="bm.urinary"]');
  ok(await page.isVisible('[data-gudenies]') && !(await page.isVisible('[data-guost="Colostomy"]')), 'one section can be opened on its own');
  // remembered: another patient, and after the app is opened again
  await page.goBack(); await page.waitForSelector('[data-act="open"]');
  await openPt(1);
  await page.click('.dchip[data-dkey="bm"]'); await page.waitForSelector('[data-sfold="bm.cath"]');
  ok(await page.isVisible('[data-gudenies]') && !(await page.isVisible('[data-gucath="Foley"]')), 'the next patient opens with the same sections folded');
  ok(!(await page.textContent('[data-sfold="bm.cath"]')).includes('Foley'), 'and that patient\'s folded heading does not show the first patient\'s catheter');
  await page.reload(); await page.waitForSelector('[data-act="open"]');
  await page.locator('[data-act="open"]').nth(0).click(); await page.waitForSelector('#note');
  await page.click('.dchip[data-dkey="bm"]'); await page.waitForSelector('[data-sfold="bm.cath"]');
  ok(await page.isVisible('[data-gudenies]') && !(await page.isVisible('[data-gucath="Foley"]')) && (await page.textContent('[data-sfold="bm.cath"]')).includes('Foley catheter in place'), 'still folded after the app is opened again, with the first patient\'s catheter in the heading');
  await tap('[data-sfoldall="bm"]'); await tap('[data-sfoldall="bm"]');
  ok(await page.isVisible('[data-gucath="Foley"]') && await page.isVisible('[data-guost="Colostomy"]'), 'Open all opens everything');
  // exam: sections per body system; "Put in note" stays on the heading
  await page.click('.dchip[data-dkey="exam"]'); await page.waitForSelector('[data-sfold="exam.Resp"]');
  ok((await page.$$('.psec')).length === 9 && (await page.$$('[data-pick="exn.sys"]')).length === 9, 'the Exam panel has a section for each of the nine systems');
  await tap('[data-exsys="Resp"][data-exv="Diminished at the bases"]'); await tap('[data-sfold="exam.Resp"]');
  ok((await page.textContent('[data-sfold="exam.Resp"]')).includes('Diminished at the bases') && await page.isVisible('[data-pick="exn.sys"][data-v="Resp"]'), 'a folded system shows its finding, and "Put in note" is still on its heading');
  await tap('[data-pick="exn.sys"][data-v="Resp"]');
  ok((await prev()).includes('On exam: Resp diminished at the bases.'), '"Put in note" works on a folded system');
  // most used
  ok(!(await page.$('#murow')), 'no Most used row before anything has been tapped three times');
  await page.click('.dchip[data-dkey="o2"]'); await page.waitForSelector('[data-o2l="2"]');
  for (let i = 0; i < 4; i++) await tap('[data-o2l="2"]:not([data-mu])');
  for (let i = 0; i < 3; i++) await tap('[data-o2sob="denies"]:not([data-mu])');
  await tap('[data-pick="o2.wean"]:not([data-mu])');
  const mu = await page.$$eval('#murow button', (els) => els.map((e) => e.textContent.trim()));
  ok(JSON.stringify(mu) === JSON.stringify(['Liters of O2: 2', 'Denies shortness of breath']), 'tapped 3 or more times: in the Most used row, most tapped first, a short one with its label: ' + JSON.stringify(mu));
  const state0 = (await prev()).includes('Pt on 2 L O2.');
  await tap('#murow [data-o2l="2"]');
  ok((await prev()).includes('Pt on 2 L O2.') !== state0, 'a Most used button does the same as the real one');
  const both = await page.$$eval('[data-o2l="2"]', (els) => els.map((e) => e.classList.contains('on')));
  ok(both.length === 2 && both[0] === both[1], 'and shows the same on / off state as the real one');
  await tap('[data-sfoldall="o2"]');
  ok(await page.isVisible('#murow [data-o2sob="denies"]') && !(await page.isVisible('[data-o2sob="denies"]:not([data-mu])')), 'with every section folded the Most used row still works');
  await tap('#murow [data-o2sob="denies"]');
  ok((await page.textContent('[data-sfold="o2.symptoms"]')).includes('Pt denies shortness of breath.') === !(await prev()).includes('Pt denies shortness of breath.') ? false : true, 'and the folded heading follows it');
  await page.screenshot({ path: require('os').tmpdir() + '/shot_mostused.png' });
  ok(errors.length === 0, 'no page errors: ' + errors.join(' | '));
  console.log(`ui 11-26C: ${pass} passed, ${fail} failed`);
  await browser.close(); process.exit(fail ? 1 : 0);
})();
